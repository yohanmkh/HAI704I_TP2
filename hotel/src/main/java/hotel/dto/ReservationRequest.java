package hotel.dto;

import java.io.Serializable;

/**
 * Coarse-grained transfer object for a hotel booking operation.
 * Utilizes nested types (TravelerDto, PaymentDto) rather than a flat structure.
 */
public class ReservationRequest implements Serializable {
    private static final long serialVersionUID = 1L;

    private String agencyId;
    private String agencySecret;
    private String offerId;
    private String requestId; // Idempotency key generated by agency (UUID)
    private TravelerDto traveler;
    private PaymentDto payment;

    public ReservationRequest() {
    }

    public ReservationRequest(String agencyId, String agencySecret, String offerId, String requestId,
                              TravelerDto traveler, PaymentDto payment) {
        this.agencyId = agencyId;
        this.agencySecret = agencySecret;
        this.offerId = offerId;
        this.requestId = requestId;
        this.traveler = traveler;
        this.payment = payment;
    }

    public String getAgencyId() {
        return agencyId;
    }

    public void setAgencyId(String agencyId) {
        this.agencyId = agencyId;
    }

    public String getAgencySecret() {
        return agencySecret;
    }

    public void setAgencySecret(String agencySecret) {
        this.agencySecret = agencySecret;
    }

    public String getOfferId() {
        return offerId;
    }

    public void setOfferId(String offerId) {
        this.offerId = offerId;
    }

    public String getRequestId() {
        return requestId;
    }

    public void setRequestId(String requestId) {
        this.requestId = requestId;
    }

    public TravelerDto getTraveler() {
        return traveler;
    }

    public void setTraveler(TravelerDto traveler) {
        this.traveler = traveler;
    }

    public PaymentDto getPayment() {
        return payment;
    }

    public void setPayment(PaymentDto payment) {
        this.payment = payment;
    }

    @Override
    public String toString() {
        // Redacts secret and relies on safe PaymentDto toString
        return "ReservationRequest{" +
                "agencyId='" + agencyId + '\'' +
                ", agencySecret='[PROTECTED]'" +
                ", offerId='" + offerId + '\'' +
                ", requestId='" + requestId + '\'' +
                ", traveler=" + (traveler != null ? (traveler.getFirstName() + " " + traveler.getLastName()) : "null") +
                ", payment=" + payment +
                '}';
    }
}
